  printf '# -*- coding: utf-8 -*-\n# Generated by the protocol buffer compiler.  DO NOT EDIT!\n# source: api.proto\n"""Generated protocol buffer code."""\n\n'
  i=0
  while [ "$i" -lt "$1" ]; do
    printf 'class Message%d:\n    __slots__ = ("field_a", "field_b", "field_c")\n    FIELD_A_NUMBER = %d\n    FIELD_B_NUMBER = %d\n    FIELD_C_NUMBER = %d\n\n    def __init__(self, field_a=None, field_b=None, field_c=None):\n        self.field_a = field_a\n        self.field_b = field_b\n        self.field_c = field_c\n\n\n' "$i" $((i * 3 + 1 + $2)) $((i * 3 + 2 + $2)) $((i * 3 + 3 + $2))
    i=$((i + 1))
  done
}
